struct SurpCmp {
    const vector<int> *S;
    SurpCmp(const vector<int> &S_): S(&S_) {
    }
    bool operator()(int a, int b) const {
        if ((*S)[a] != (*S)[b]) return (*S)[a] > (*S)[b];
        return a < b;
    }
};

struct CapHeadCmp {
    bool operator()(const std::pair<int, int> &a, const std::pair<int, int> &b) const {
        if (a.first != b.first) return a.first > b.first; // room descend
        return a.second < b.second; // layer ascend
    }
};

void BuildTargetsCappedWaterfillPrefix(int R, int K, int M, const vector<int> &Cap, vector<int> &T) {
    if (R <= 0) return;
    vector<char> active(K, 0);
    int act_cnt = 0;
    for (int l = 0; l < R; l++) {
        active[l] = 1;
        ++act_cnt;
    }
    int remain = M;
    for (;;) {
        if (act_cnt <= 0) break;
        int base = (act_cnt > 0 ? (remain / act_cnt) : 0);
        bool saturated = false;
        for (int l = 0; l < R; l++) {
            if (active[l]) {
                if (Cap[l] <= base) {
                    T[l] = Cap[l];
                    remain -= T[l];
                    active[l] = 0;
                    --act_cnt;
                    saturated = true;
                }
            }
        }
        if (!saturated) {
            for (int l = 0; l < R; l++) {
                if (active[l]) T[l] = base;
            }
            int rem = remain - base * act_cnt;
            if (rem > 0) {
                vector<std::pair<int, int> > head;
                head.reserve(act_cnt);
                for (int l = 0; l < R; l++) {
                    if (active[l]) {
                        int room = Cap[l] - T[l];
                        if (room < 0) room = 0;
                        head.push_back(std::make_pair(room, l));
                    }
                }
                std::sort(head.begin(), head.end(), CapHeadCmp());
                for (int i = 0; i < rem && i < CVT_INT(head.size()); i++) {
                    int l = head[i].second;
                    if (T[l] < Cap[l]) T[l] += 1;
                }
            }
            break;
        }
    }
}

// Static theoretic capacity of each layer
void ComputeLayerCaps(int N, int K, const vector<int> &Lmin, const vector<int> &Lmax, vector<int> &Cap) {
    Cap.assign(K, 0);
    for (int u = 0; u < N; u++) {
        int a = Lmin[u];
        int b = Lmax[u];
        if (a < 0) a = 0;
        if (b >= K) b = K - 1;
        for (int l = a; l <= b; ++l) {
            ++Cap[l];
        }
    }
}

int AutoDetectFixedSuffix_PrefixDynamic(const vector<vector<int> > &Buckets, const vector<int> &Count,
                                        const vector<int> &low, const vector<int> &high) {
    const int K = CVT_INT(Buckets.size());
    int R = 0;
    for (int l = K - 1; l >= 0; l--) {
        bool can_evac_up = false;
        for (size_t i = 0; i < Buckets[l].size(); i++) {
            int u = Buckets[l][i];
            if (low[u] < l) {
                can_evac_up = true;
                break;
            }
        }
        if (can_evac_up) break;

        int cap_prefix = 0;
        for (int x = 0; x <= l; x++) {
            const vector<int> &V = Buckets[x];
            for (size_t j = 0; j < V.size(); j++) {
                int v = V[j];
                if (low[v] <= l && l <= high[v]) cap_prefix++;
            }
        }
        if (cap_prefix == Count[l]) {
            ++R;
        } else {
            break;
        }
    }
    return R;
}

int AutoDetectFixedSuffix_Heuristic(int N, int K, bool fix_last, const vector<vector<int> > &Buckets,
                                    const vector<int> &Count, const vector<int> &low_dyn,
                                    const vector<int> *low_star_opt) {
    int last_ct = Count[K - 1];
    int Np = N;
    int tau = (K - 1) ? (Np / K) : 0;
    if (fix_last) {
        Np = N - last_ct;
        tau = (K - 1) ? (Np / (K - 1)) : 0;
    }

    int R = 0;
    for (int l = K - 1; l >= 0; l--) {
        const vector<int> &V = Buckets[l];
        int cnt = Count[l];

        if (cnt <= tau) {
            ++R;
            continue;
        } // not crowd, fixed directly

        bool exists_movable_up = false;
        for (size_t i = 0; i < V.size(); i++) {
            int u = V[i];
            if (low_dyn[u] < l) {
                exists_movable_up = true;
                break;
            }
            if (low_star_opt && (*low_star_opt)[u] < l) {
                exists_movable_up = true;
                break;
            }
        }
        if (!exists_movable_up) {
            ++R; // more but cannot move => fixed
        } else {
            break; // more and movable => stop here
        }
    }
    return R;
}

// Check how many lowest layers can be fixed during balancing layering
int AutoDetectFixedSuffix(const vector<vector<int> > &Buckets, const vector<int> &Lmin,
                          const vector<int> &Lmax, const vector<int> &Cap) {
    const int K = CVT_INT(Buckets.size());
    int fixed_suffix = 0;
    for (int l = K - 1; l >= 0; l--) {
        bool no_evac_up = true;
        for (size_t i = 0; i < Buckets[l].size(); i++) {
            int u = Buckets[l][i];
            if (Lmin[u] < l) {
                no_evac_up = false;
                break;
            }
        }
        bool no_headroom_in = (CVT_INT(Buckets[l].size()) == Cap[l]);
        if (no_evac_up && no_headroom_in) {
            ++fixed_suffix;
        } else break;
    }
    return fixed_suffix; // may be 0
}

int AutoDetectDynamicFixedSuffix(const vector<vector<int> > &Buckets,
                                 const vector<int> &low, const vector<int> &high,
                                 const vector<int> &mov_up, const vector<int> &mov_down,
                                 bool require_low_eq_high) {
    int K = CVT_INT(Buckets.size());
    int R = 0;
    for (int l = K - 1; l >= 0; l--) {
        bool dyn_lock = (mov_up[l] == 0 && mov_down[l] == 0);
        if (dyn_lock && require_low_eq_high) {
            for (size_t i = 0; i < Buckets[l].size(); i++) {
                int u = Buckets[l][i];
                if (!(low[u] == high[u] && low[u] == l)) {
                    dyn_lock = false;
                    break;
                }
            }
        }
        if (dyn_lock) ++R;
        else break;
    }
    return R;
}

/* prefix cap excluding suffix */
void ComputePrefixCapsExcludingSuffix(int N, int K, int prefix_end, const vector<int> &L,
                                      const vector<int> &Lmin, const vector<int> &Lmax, vector<int> &CapPrefix) {
    if (prefix_end <= 0) return;
    CapPrefix.assign(K, 0);
    for (int u = 0; u < N; u++) {
        if (L[u] < 0) continue;
        if (L[u] >= prefix_end) continue; // cell locates in fixed_suffix
        int a = Lmin[u];
        if (a < 0) a = 0;
        int b = Lmax[u];
        if (b >= K) b = K - 1;
        if (b < 0 || a >= K) continue;
        int Ls = (a > 0 ? a : 0);
        int Rs = (b < prefix_end - 1 ? b : (prefix_end - 1));
        if (Ls > Rs) continue;
        for (int l = Ls; l <= Rs; ++l)
            ++CapPrefix[l];
    }
}


int NearestDeficitLayer(int s, const vector<int> &S) {
    int K = CVT_INT(S.size());
    for (int dlt = 1; dlt < K; ++dlt) {
        int r = s + dlt, l = s - dlt;
        if (r < K && S[r] < 0) return r; // prefer the nearest downstream deficit layer
        if (l >= 0 && S[l] < 0) return l;
    }
    return -1;
}

// from layer s to layer d, find the nearest layer that between low_u and high_u, and S[t]<0; otherwise return -1
int PickNearestDeficitTarget(int s, int d, const vector<int> &S, int low_u, int high_u, int prefix_end) {
    if (d == s) return -1;
    int dir = (d > s) ? 1 : -1;
    for (int t = s + dir; (dir > 0 ? t <= d : t >= d); t += dir) {
        if (t >= prefix_end) break; // cannot enter frozen suffix
        if (t < low_u || t > high_u) continue;
        if (S[t] < 0) return t;
    }
    return -1;
}

int NeighborTightenRisk(int u, int t, int K, const vector<vector<int> > &Up, const vector<vector<int> > &Down,
                        const vector<int> &L, const vector<int> &low, const vector<int> &high,
                        const vector<int> &Lmin, const vector<int> &Lmax) {
    int risk = 0;
    // downstream: moving u to layer t will affect u's downstream's lowerst layerID
    for (size_t i = 0; i < Down[u].size(); i++) {
        // u's downstream cell
        int c = Down[u][i];
        int max_up = INT_MIN;
        for (size_t j = 0; j < Up[c].size(); j++) {
            // c's upstream cell
            int p = Up[c][j];
            int val = (p == u ? t : L[p]);
            if (val > max_up) max_up = val;
        }
        int new_low = (max_up == INT_MIN ? 0 : max_up + 1);
        if (new_low < Lmin[c]) new_low = Lmin[c];
        if (new_low < 0) new_low = 0;
        if (new_low > low[c]) risk++;
    }
    // upstream: moving u to layer t will affect u's upstream's highest layerID
    for (size_t i = 0; i < Up[u].size(); ++i) {
        // u's upstream cell
        int p = Up[u][i];
        int min_dn = INT_MAX;
        for (size_t j = 0; j < Down[p].size(); ++j) {
            // p's downstream cell
            int c = Down[p][j];
            int val = (c == u ? t : L[c]);
            if (val < min_dn) min_dn = val;
        }
        int new_high = (min_dn == INT_MAX ? (K - 1) : min_dn - 1);
        if (new_high > Lmax[p]) new_high = Lmax[p];
        if (new_high >= K) new_high = K - 1;
        if (new_high < high[p]) risk++;
    }
    return risk;
}

void CollectCandidates(int s, int d, int K, int prefix_end, const vector<vector<int> > &Buckets,
                       const vector<int> &L, const vector<int> &low, const vector<int> &high,
                       const vector<int> &Lmin, const vector<int> &Lmax,
                       const vector<vector<int> > &Up, const vector<vector<int> > &Down,
                       const vector<int> &S, bool require_deficit_target, const vector<int> *pCap,
                       int capMin, int capMax, double depth_penalty_weight, double scarcity_weight,
                       vector<Candidate> &out) {
    static const double A = 5.0; // slack
    static const double B = 2.0; // window
    static const double Cw = 1.0; // gateway
    static const double D = 1.0; // dist penalty
    static const double E = 2.0; // risk penalty
    static const double tiny = 1e-6;

    out.clear();
    const vector<int> &nodes = Buckets[s];

    for (size_t idx = 0; idx < nodes.size(); idx++) {
        int u = nodes[idx];
        int t = -1;

        if (require_deficit_target) {
            t = PickNearestDeficitTarget(s, d, S, low[u], high[u], prefix_end);
            if (t < 0) continue;
        } else {
            if (d > s) {
                int mh = (high[u] < d ? high[u] : d);
                int step = mh - s;
                if (step <= 0) continue;
                int need = Abs(d - s);
                if (step > need) step = need;
                t = s + step;
            } else if (d < s) {
                int ml = (low[u] > d ? low[u] : d);
                int step = s - ml;
                if (step <= 0) continue;
                int need = Abs(d - s);
                if (step > need) step = need;
                t = s - step;
            } else continue;
        }
        if (t >= prefix_end) continue; // forbid moving into frozen suffix

        int slk = Abs(t - s);
        int window = high[u] - low[u];
        if (window < 0) window = 0;
        int dist_penalty = Abs(t - d);
        int risk = NeighborTightenRisk(u, t, K, Up, Down, L, low, high, Lmin, Lmax);

        double score = 0.0;
        score += A * (double) slk;
        score += B * (double) window;
        if (Up[u].size() >= 2 || Down[u].size() >= 2) score += Cw;
        score -= D * (double) dist_penalty;
        score -= E * (double) risk;
        // downstream friction (optional)
        if (depth_penalty_weight > 0.0) {
            score -= depth_penalty_weight * (double) t;
        }
        // scarcity-based penalty (optional)
        if (pCap && scarcity_weight > 0.0 && capMax > capMin) {
            int cap_t = (*pCap)[t];
            double scarcity = 1.0 - (double) (cap_t - capMin) / (double) (capMax - capMin);
            score -= scarcity_weight * scarcity;
        }
        score -= tiny * (double) u;

        Candidate c;
        c.u = u;
        c.score = score;
        c.slack = slk;
        c.window = window;
        c.t = t;
        out.push_back(c);
    }
    std::sort(out.begin(), out.end(), CandidateCmp());
}


bool PickFeasibleDeficitAndCandidates(int s, const vector<int>& S, int K, int prefix_end,
                                      const vector<vector<int> >& Buckets,
                                      const vector<int>& L,
                                      const vector<int>& low, const vector<int>& high,
                                      const vector<int>& Lmin, const vector<int>& Lmax,
                                      const vector<vector<int> >& Up,
                                      const vector<vector<int> >& Down,
                                      bool strict_deficit_target,
                                      bool allow_intermediate_fallback,
                                      int& d_out,
                                      vector<Candidate>& cand_out,
                                      DeficitScanMode mode,
                                      const vector<int>* pCap,
                                      int capMin, int capMax,
                                      double depth_penalty_weight,
                                      double scarcity_weight) {
    vector<int> deficits;
    for (int l = 0; l < K; ++l) if (S[l] < 0) deficits.push_back(l);
    if (deficits.empty()) return false;

    if (mode == BIGGEST_DEFICIT_FIRST) {
        std::sort(deficits.begin(), deficits.end(), BigDefCmp(S, s));
        if (strict_deficit_target) {
            for (size_t i = 0; i < deficits.size(); ++i) {
                int d = deficits[i];
                cand_out.clear();
                CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                                  true, pCap, capMin, capMax,
                                  depth_penalty_weight, scarcity_weight, cand_out);
                if (!cand_out.empty()) {
                    d_out = d;
                    return true;
                }
            }
        }
        if (allow_intermediate_fallback) {
            for (size_t i = 0; i < deficits.size(); ++i) {
                int d = deficits[i];
                cand_out.clear();
                CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                                  false, pCap, capMin, capMax,
                                  depth_penalty_weight, scarcity_weight, cand_out);
                if (!cand_out.empty()) {
                    d_out = d;
                    return true;
                }
            }
        }
        return false;
    }

    vector<std::pair<int, int> > order;
    order.reserve(deficits.size());
    for (size_t i = 0; i < deficits.size(); ++i) {
        int d = deficits[i];
        order.push_back(std::make_pair(std::abs(d - s), d));
    }
    DistOrderCmp cmp(s, (mode == FARTHEST_FIRST));
    std::sort(order.begin(), order.end(), cmp);

    if (mode != BEST_BATCH_SCORE) {
        if (strict_deficit_target) {
            for (size_t i = 0; i < order.size(); ++i) {
                int d = order[i].second;
                cand_out.clear();
                CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                                  true, pCap, capMin, capMax,
                                  depth_penalty_weight, scarcity_weight, cand_out);
                if (!cand_out.empty()) {
                    d_out = d;
                    return true;
                }
            }
        }
        if (allow_intermediate_fallback) {
            for (size_t i = 0; i < order.size(); ++i) {
                int d = order[i].second;
                cand_out.clear();
                CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                                  false, pCap, capMin, capMax,
                                  depth_penalty_weight, scarcity_weight, cand_out);
                if (!cand_out.empty()) {
                    d_out = d;
                    return true;
                }
            }
        }
        return false;
    }

    int best_d = -1;
    double best_sum = -1e100;
    vector<Candidate> best_cand;

    for (size_t i = 0; i < order.size(); ++i) {
        int d = order[i].second;
        int need = 0; {
            int s_pos = S[s];
            int d_neg = -S[d];
            need = (s_pos < d_neg ? s_pos : d_neg);
        }
        if (need <= 0) continue;

        vector<Candidate> tmp;
        if (strict_deficit_target) {
            CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                              true, pCap, capMin, capMax,
                              depth_penalty_weight, scarcity_weight, tmp);
            if (!tmp.empty()) {
                int take = (int) tmp.size();
                if (take > need) take = need;
                double sum = 0.0;
                for (int k = 0; k < take; ++k) sum += tmp[k].score;
                if (sum > best_sum) {
                    best_sum = sum;
                    best_d = d;
                    best_cand = tmp;
                }
            }
        }
        if (allow_intermediate_fallback) {
            tmp.clear();
            CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                              false, pCap, capMin, capMax,
                              depth_penalty_weight, scarcity_weight, tmp);
            if (!tmp.empty()) {
                int take = (int) tmp.size();
                if (take > need) take = need;
                double sum = 0.0;
                for (int k = 0; k < take; ++k) sum += tmp[k].score;
                if (sum > best_sum) {
                    best_sum = sum;
                    best_d = d;
                    best_cand = tmp;
                }
            }
        }
    }
    if (best_d < 0) return false;
    d_out = best_d;
    cand_out = best_cand;
    return true;
}

void EvaluateBatchPotentialCounts(int s, const vector<Candidate> &cand, int need,
                                  const vector<int> &Count, const vector<int> &T,
                                  long long &phi1, long long &psi1) {
    vector<int> Ctmp = Count;
    int take = CVT_INT(cand.size());
    if (take > need) take = need;
    for (int k = 0; k < take; k++) {
        int t = cand[k].t;
        Ctmp[s] -= 1;
        Ctmp[t] += 1;
    }
    phi1 = Phi_L1(Ctmp, T);
    psi1 = Psi_L2(Ctmp, T);
}

void EvaluateBatchPotentialCountsPrefix(int s, const vector<Candidate> &cand, int need,
                                        const vector<int> &Count, const vector<int> &T,
                                        int prefix_end, long long &phi1_pref, long long &psi1_pref) {
    vector<int> Ctmp = Count;
    int take = CVT_INT(cand.size());
    if (take > need) take = need;
    for (int k = 0; k < take; k++) {
        int t = cand[k].t;
        Ctmp[s] -= 1;
        Ctmp[t] += 1;
    }
    phi1_pref = Phi_L1_Prefix(Ctmp, T, prefix_end);
    psi1_pref = Psi_L2_Prefix(Ctmp, T, prefix_end);
}

bool PickDeficitByPotentialAuto(int s, const vector<int> &S, int K, int prefix_end,
                                const vector<vector<int> > &Buckets,
                                const vector<int> &L, const vector<int> &low, const vector<int> &high,
                                const vector<int> &Lmin, const vector<int> &Lmax,
                                const vector<vector<int> > &Up, const vector<vector<int> > &Down,
                                const vector<int> &Count, const vector<int> &T,
                                bool allow_intermediate_fallback,
                                int &d_out, vector<Candidate> &cand_out,
                                const vector<int> *pCap, int capMin, int capMax,
                                double depth_penalty_weight, double scarcity_weight) {
    vector<int> deficits;
    for (int l = 0; l < prefix_end; l++) {
        if (S[l] < 0) deficits.push_back(l);
    }
    if (deficits.empty()) return false;

    long long best_phi = LLONG_MAX;
    long long best_psi = LLONG_MAX;
    int best_d = -1;
    vector<Candidate> best_cand;

    for (size_t i = 0; i < deficits.size(); ++i) {
        int d = deficits[i];
        int need = (S[s] < -S[d] ? S[s] : -S[d]);
        if (need <= 0) continue;

        // first try strictly allocate
        vector<Candidate> tmp;
        CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                          /*require_deficit_target=*/true,
                          pCap, capMin, capMax, depth_penalty_weight, scarcity_weight, tmp);
        if (!tmp.empty()) {
            long long phi1;
            long long psi1;
            // EvaluateBatchPotentialCounts(s, tmp, need, Count, T, phi1, psi1);
            EvaluateBatchPotentialCountsPrefix(s, tmp, need, Count, T, prefix_end, phi1, psi1);
            if (phi1 < best_phi || (phi1 == best_phi && psi1 < best_psi)) {
                best_phi = phi1;
                best_psi = psi1;
                best_d = d;
                best_cand = tmp;
            }
            continue; // if we got valid solution, then do not need to use fallback
        }

        // fallback: allowing to allocate in the intermediate layers
        if (allow_intermediate_fallback) {
            tmp.clear();
            CollectCandidates(s, d, K, prefix_end, Buckets, L, low, high, Lmin, Lmax, Up, Down, S,
                              /*require_deficit_target=*/false,
                              pCap, capMin, capMax, depth_penalty_weight, scarcity_weight, tmp);
            if (!tmp.empty()) {
                long long phi1;
                long long psi1;
                // EvaluateBatchPotentialCounts(s, tmp, need, Count, T, phi1, psi1);
                EvaluateBatchPotentialCountsPrefix(s, tmp, need, Count, T, prefix_end, phi1, psi1);
                if (phi1 < best_phi || (phi1 == best_phi && psi1 < best_psi)) {
                    best_phi = phi1;
                    best_psi = psi1;
                    best_d = d;
                    best_cand = tmp;
                }
            }
        }
    }

    if (best_d < 0) return false;
    d_out = best_d;
    cand_out = best_cand;
    return true;
}

bool TryEvictAndFillOnce(const vector<int> &S, int K, int prefix_end,
                         vector<vector<int> > &Buckets, vector<int> &L, vector<int> &Count,
                         const vector<int> &Lmin, const vector<int> &Lmax,
                         const vector<vector<int> > &Up, const vector<vector<int> > &Down,
                         vector<int> &low, vector<int> &high, const vector<int> &T) {
    vector<int> Surp;
    for (int l = 0; l < prefix_end; l++) {
        if (S[l] > 0) Surp.push_back(l);
    }
    if (Surp.empty()) return false;
    std::sort(Surp.begin(), Surp.end(), SurpCmp(S));
#ifdef _DEBUG
    std::printf("  [EVF] try: prefix_end=%d, SurpCnt=%d\n", prefix_end, (int)Surp.size());
#endif

    for (size_t si = 0; si < Surp.size(); si++) {
        int s = Surp[si];
        for (int b = 0; b < prefix_end; b++) {
            /* allow deficit layers as buffer */
            if (S[b] > 0) continue; // buffer can be balanced (S==0) or deficit (S<0)

            if (Buckets[s].empty() || Buckets[b].empty()) continue;

            // v: from s -> b
            vector<Candidate> cand_v;
            for (size_t i = 0; i < Buckets[s].size(); i++) {
                int v = Buckets[s][i];
                if (low[v] <= b && b <= high[v]) {
                    int window = high[v] - low[v];
                    if (window < 0) window = 0;
                    int slk = Abs(b - s);
                    int risk = NeighborTightenRisk(v, b, K, Up, Down, L, low, high, Lmin, Lmax);
                    double score = 5.0 * slk + 2.0 * window - 2.0 * risk - 1e-6 * v;
                    Candidate c;
                    c.u = v;
                    c.t = b;
                    c.slack = slk;
                    c.window = window;
                    c.score = score;
                    cand_v.push_back(c);
                }
            }
            if (cand_v.empty()) continue;
            std::sort(cand_v.begin(), cand_v.end(), CandidateCmp());

            // u: from b -> t_u (t_u in prefix, defict or balanced)
            vector<UPick> cand_u;
            for (size_t i = 0; i < Buckets[b].size(); i++) {
                int u = Buckets[b][i];
                for (int t = low[u]; t <= high[u]; t++) {
                    if (t == b) continue;
                    if (t >= prefix_end) continue;
                    if (S[t] > 0) continue;
                    /* optional: when buffer b is deficit, skip sending u to balanced */
                    if (S[b] < 0 && S[t] == 0) continue;

                    int slk = Abs(t - b);
                    int window = high[u] - low[u];
                    if (window < 0) window = 0;
                    int risk = NeighborTightenRisk(u, t, K, Up, Down, L, low, high, Lmin, Lmax);
                    double score = 5.0 * slk + 2.0 * window - 2.0 * risk - 1e-6 * u;
                    UPick pick;
                    pick.u = u;
                    pick.t = t;
                    pick.slack = slk;
                    pick.window = window;
                    pick.score = score;
                    cand_u.push_back(pick);
                }
            }
            if (cand_u.empty()) continue;
            std::sort(cand_u.begin(), cand_u.end(), UPickCmp());

            const int M = 8;
            int v_lim = CVT_INT(cand_v.size());
            if (v_lim > M) v_lim = M;
            int u_lim = CVT_INT(cand_u.size());
            if (u_lim > M) u_lim = M;

            long long best_phi1 = LLONG_MAX;
            long long best_psi1 = LLONG_MAX;
            int best_v = -1;
            int best_u = -1;
            int best_tu = -1;

            for (int iv = 0; iv < v_lim; iv++) {
                int v = cand_v[iv].u;
                for (int iu = 0; iu < u_lim; iu++) {
                    int u2 = cand_u[iu].u;
                    int t_u = cand_u[iu].t;
                    if (u2 == v) continue;

                    vector<int> Ctmp = Count;
                    Ctmp[s]--; // v: s -> b
                    Ctmp[b]++; // temp
                    Ctmp[b]--; // u: b -> t_u
                    Ctmp[t_u]++;

                    long long phi1 = Phi_L1_Prefix(Ctmp, T, prefix_end);
                    long long psi1 = Psi_L2_Prefix(Ctmp, T, prefix_end);
                    if (phi1 < best_phi1 || (phi1 == best_phi1 && psi1 < best_psi1)) {
                        best_phi1 = phi1;
                        best_psi1 = psi1;
                        best_v = v;
                        best_u = u2;
                        best_tu = t_u;
                    }
                }
            }

            if (best_v >= 0 && best_u >= 0) {
                // long long phi0 = Phi_L1(Count, T);
                // long long psi0 = Psi_L2(Count, T);
                long long phi0_pref = Phi_L1_Prefix(Count, T, prefix_end);
                long long psi0_pref = Psi_L2_Prefix(Count, T, prefix_end);
                vector<int> Ctmp = Count;
                Ctmp[s]--; // v: s -> b
                Ctmp[b]++; // temp
                Ctmp[b]--; // u: b -> t_u
                Ctmp[best_tu]++;
                long long phi1_pref = Phi_L1_Prefix(Ctmp, T, prefix_end);
                long long psi1_pref = Psi_L2_Prefix(Ctmp, T, prefix_end);

                if (phi1_pref < phi0_pref || (phi1_pref == phi0_pref && psi1_pref < psi0_pref)) {
#ifdef _DEBUG
                    std::printf("  [EVF] ACCEPT: s=%d  b=%d  v:%d -> %d  u:%d -> %d  Phi_pref:%lld->%lld Psi_pref:%lld->%lld\n",
                        s, b, best_v, b, best_u, best_tu, phi0_pref, phi1_pref, psi0_pref, psi1_pref);
#endif
                    // real execute
                    vector<int> moved;
                    PlaceOne(best_u, best_tu, L, Buckets, Count);
                    moved.push_back(best_u);
                    PlaceOne(best_v, b, L, Buckets, Count);
                    moved.push_back(best_v);
                    RefreshLocalBounds(moved, K, Up, Down, L, Lmin, Lmax, low, high);
                    return true; // accept and exit
                } else {
                    continue; // don't exit; try next (s, b)
                }
            }
        }
    }
    return false;
}

// ---------- Move one cell from source layer to target layer ----------
void PlaceOne(int u, int t, vector<int> &L, vector<vector<int> > &Buckets, vector<int> &Count) {
    int s = L[u];
    if (s == t) return; // source layer is the same with target layer
    vector<int> &src = Buckets[s];
    for (size_t i = 0; i < src.size(); i++) {
        if (src[i] == u) {
            src.erase(src.begin() + (int) i);
            break;
        }
    }
    Buckets[t].push_back(u);
    Count[s]--;
    Count[t]++;
    L[u] = t;
}

static void RefreshLocalBounds(const vector<int> &moved, int K,
                               const vector<vector<int> > &Up, const vector<vector<int> > &Down,
                               const vector<int> &L, const vector<int> &Lmin, const vector<int> &Lmax,
                               vector<int> &low, vector<int> &high) {
    const int N = CVT_INT(L.size());
    std::queue<int> q;
    vector<char> inq(N, 0);
    for (size_t i = 0; i < moved.size(); i++) {
        int u = moved[i];
        if (!inq[u]) {
            q.push(u);
            inq[u] = 1;
        }
        for (size_t j = 0; j < Up[u].size(); j++) {
            int p = Up[u][j];
            if (!inq[p]) {
                q.push(p);
                inq[p] = 1;
            }
        }
        for (size_t j = 0; j < Down[u].size(); j++) {
            int c = Down[u][j];
            if (!inq[c]) {
                q.push(c);
                inq[c] = 1;
            }
        }
    }
    while (!q.empty()) {
        int x = q.front();
        q.pop();
        inq[x] = 0;
        int nl;
        int nh;
        RecomputeBoundsOne(x, K, Up, Down, L, Lmin, Lmax, nl, nh);
        if (nl != low[x] || nh != high[x]) {
            low[x] = nl;
            high[x] = nh;
            for (size_t j = 0; j < Up[x].size(); j++) {
                int p = Up[x][j];
                if (!inq[p]) {
                    q.push(p);
                    inq[p] = 1;
                }
            }
            for (size_t j = 0; j < Down[x].size(); j++) {
                int c = Down[x][j];
                if (!inq[c]) {
                    q.push(c);
                    inq[c] = 1;
                }
            }
        }
    }
}

