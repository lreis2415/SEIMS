void GridLayering::CountFlowOutCells(int mode/*=0*/) {
    if (nullptr != flow_out_num_) Release1DArray(flow_out_num_);
    Initialize1DArray(n_valid_cells_, flow_out_num_, -1);
    if (nullptr != flow_out_acc_) Release1DArray(flow_out_acc_);
    Initialize1DArray(n_valid_cells_, flow_out_acc_, 0);
    //bool handle_stream = force_outlet_ && nullptr != stream_matrix_;
//#pragma omp parallel for
    for (int index = 0; index < n_valid_cells_; index++) {
        int i = pos_rowcol_[index][0]; // row
        int j = pos_rowcol_[index][1]; // col
        if (flowdir_->IsNoData(i, j) || flowdir_matrix_[index] < 0) continue;
        int stream_src = mode != 0 ? stream_matrix_[index]: -1;
        if (mode == 2 && FloatEqual(stream_src, out_nodata_)) continue;

        if (flow_out_num_[index] == -1) flow_out_num_[index] = 0;

        int flow_dir = flowdir_matrix_[index];
        vector<int> flow_dirs = uncompress_flow_directions(flow_dir);
        int org_down_num = flow_dirs.size();
        for (vector<int>::iterator it = flow_dirs.begin(); it != flow_dirs.end(); ++it) {
            int fd_idx = find_flow_direction_index_ccw(*it);
            int dst_row = i + drow[fd_idx];
            int dst_col = j + dcol[fd_idx];
            if (!mask_->ValidateRowCol(dst_row, dst_col) || mask_->IsNoData(dst_row, dst_col)) {
                // means flow out of the mask boundary, so we should remove this direction
                // Here, we only handle the flow direction, this is unrelated with flow direction algorithms.
                // For multiple flow direction algorithms, the flow fractions should be handled in other places.
                flowdir_matrix_[index] -= (*it);
                continue;
            }
            int dst_idx = pos_index_[dst_row * n_cols_ + dst_col];
            int stream_dst = mode == 1 ? stream_matrix_[dst_idx] : -1;
            if (mode == 1 && stream_src > 0 && stream_dst > 0) {
                continue;
            }
            flow_out_num_[index]++;
        }
        // Some flow direction data may cause errors after checking if all downslope cells are within mask
        // For example:
        //            (5,23)
        //            (6,23) (6,24)
        //            (7,23) (7,24) (7,25)
        //   Dinf: (6,24) has two downslope: (5,23) and (6,23), and both are outside the mask (subbasin)
        //   In fact, (7,25)'s elevation almost equals to (5,23), which is inside the mask.
        //   Due to the characteristics of Dinf algorithm, the (7,25) cannot be the downslope of (6,24)
        //   In such case, we should manually make the downslope of (6,25) -> (7,25) using elevation data
        //
        if (org_down_num >= 2 && flow_out_num_[index] == 0 && !(mode == 1 && stream_src > 0)) {
            FLTPT dem_diff = 0.;
            int max_flowidx = -1;
            FLTPT dem_dst;
            FLTPT dem_src = dem_->GetValue(i, j);
            for (int ii = 1; ii <= 8; ii++) {
                int dst_row = i + drow[ii];
                int dst_col = j + dcol[ii];
                if (!mask_->ValidateRowCol(dst_row, dst_col) || mask_->IsNoData(dst_row, dst_col)) {
                    continue;
                }
                dem_dst = dem_->GetValue(dst_row, dst_col);
                if (dem_src - dem_dst >= dem_diff) {
                    dem_diff = dem_src - dem_dst;
                    max_flowidx = ii;
                }
            }
            if (max_flowidx > 0) {
                flow_out_num_[index] = 1;
                flowdir_matrix_[index] = fdccw[max_flowidx];
            } else {
                cout << "The cell " << index << " cannot flow inside the mask, please check!" << endl;
            }
        }
    }
    flow_out_acc_[0] = flow_out_num_[0] < 0 ? 0 : flow_out_num_[0];
    flow_out_count_ = flow_out_num_[0] < 0 ? 0 : flow_out_num_[0];
    for (int idx = 1; idx < n_valid_cells_; idx++) {
        if (flow_out_num_[idx] == -1) {
            flow_out_acc_[idx] = flow_out_acc_[idx - 1];
            continue;
        }
        flow_out_count_ += flow_out_num_[idx];
        flow_out_acc_[idx] = flow_out_num_[idx] + flow_out_acc_[idx - 1];
    }
}

